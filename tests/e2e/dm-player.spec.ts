import { test, expect } from '@playwright/test'
import { PNG_1X1 } from '../fixtures/image'

test.skip(!process.env.NEXT_PUBLIC_SUPABASE_URL || !process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY, 'Requires a Realtime test project')

test('DM and Player share a token move and dice roll', async ({ browser }) => {
  const dm = await browser.newContext()
  const player = await browser.newContext()
  try {
    const dmPage = await dm.newPage()
    const playerPage = await player.newPage()
    await dmPage.goto('/')
    await dmPage.getByRole('button', { name: 'Crear sala' }).click()
    await expect(dmPage.getByText('En vivo')).toBeVisible()
    await playerPage.goto(dmPage.url())
    await playerPage.getByLabel('Nombre').fill('Juan')
    await playerPage.getByRole('button', { name: 'Entrar' }).click()
    await expect(playerPage.locator('[data-token-id]').first()).toBeVisible()
    const token = playerPage.locator('[data-token-id]').first()
    const before = await token.getAttribute('style')
    const rect = await token.boundingBox()
    if (!rect) throw new Error('Token missing')
    await playerPage.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2)
    await playerPage.mouse.down()
    await playerPage.mouse.move(rect.x + rect.width / 2 + 80, rect.y + rect.height / 2 + 40, { steps: 5 })
    await playerPage.mouse.up()
    await expect(token).not.toHaveAttribute('style', before ?? '')
    const tokenId = await token.getAttribute('data-token-id')
    await expect(dmPage.locator(`[data-token-id="${tokenId}"]`)).toHaveAttribute('style', await token.getAttribute('style') ?? '')
    await playerPage.getByRole('button', { name: 'Tirar' }).click()
    await expect(dmPage.locator('.dice-history li').first()).toContainText('Juan')
    await dmPage.locator('input[type="file"][accept="image/jpeg,image/png,image/webp"]').first().setInputFiles({ name: 'map.png', mimeType: 'image/png', buffer: Buffer.from(PNG_1X1, 'base64') })
    await expect(playerPage.getByAltText('Mapa de la partida')).toBeVisible()
    const [download] = await Promise.all([dmPage.waitForEvent('download'), dmPage.getByRole('button', { name: 'Exportar JSON' }).click()])
    const exported = await download.path()
    if (!exported) throw new Error('Export missing')
    await dmPage.goto('/')
    await dmPage.getByRole('button', { name: 'Crear sala' }).click()
    await expect(dmPage.getByText('En vivo')).toBeVisible()
    await dmPage.locator('input[type="file"][accept="application/json,.json"]').setInputFiles(exported)
    await expect(dmPage.getByAltText('Mapa de la partida')).toBeVisible()
    await playerPage.goto(dmPage.url())
    await playerPage.getByLabel('Nombre').fill('Juan')
    await playerPage.getByRole('button', { name: 'Entrar' }).click()
    await expect(playerPage.getByAltText('Mapa de la partida')).toBeVisible()
    await expect(playerPage.locator('[data-token-id]')).toHaveCount(1)
  } finally { await dm.close(); await player.close() }
})
