import { expect, test } from '@playwright/test'

test.skip(!process.env.NEXT_PUBLIC_SUPABASE_URL || !process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY, 'Requires a Realtime test project')

test('DM tool controls and select-mode drag pan the canvas without a pan tool', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Crear sala' }).click()
  await expect(page.getByText('En vivo')).toBeVisible()
  const board = page.getByLabel('Tablero')
  await expect(board).toHaveClass(/board-tool-select/)
  await expect(board).toHaveCSS('cursor', 'grab')
  await page.keyboard.press('p')
  await expect(board).toHaveClass(/board-tool-pencil/)
  await expect(board).toHaveCSS('cursor', /pencil\.svg/)
  await page.keyboard.press('e')
  await expect(board).toHaveClass(/board-tool-eraser/)
  await page.keyboard.press('h')
  await expect(board).toHaveClass(/board-tool-eraser/)
  await page.getByRole('button', { name: 'Seleccionar' }).click()
  await expect(board).toHaveClass(/board-tool-select/)
  const world = board.locator('.world')
  const initialTransform = await world.getAttribute('style')
  const bounds = await board.boundingBox()
  if (!bounds) throw new Error('Board is not visible')
  await page.mouse.move(bounds.x + 120, bounds.y + 120)
  await page.mouse.down()
  await page.mouse.move(bounds.x + 190, bounds.y + 170, { steps: 4 })
  await page.mouse.up()
  await expect(board).toHaveClass(/board-tool-select/)
  await expect(world).not.toHaveAttribute('style', initialTransform ?? '')
  await page.getByLabel('Nombre').count().then(count => expect(count).toBe(0))
  await page.keyboard.press('v')
  await expect(board).toHaveClass(/board-tool-select/)
})
