import { expect, test } from '@playwright/test'
import { PNG_1X1 } from '../fixtures/image'

test.skip(!process.env.NEXT_PUBLIC_SUPABASE_URL || !process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY, 'Requires a Realtime test project')

test('DM adds, selects and deletes a standalone board image', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Crear sala' }).click()
  await expect(page.getByText('En vivo')).toBeVisible()
  await page.getByRole('button', { name: 'Agregar imagen al tablero' }).click()
  await page.locator('#board-image-input').setInputFiles({ name: 'marker.png', mimeType: 'image/png', buffer: Buffer.from(PNG_1X1, 'base64') })
  const image = page.locator('[data-board-image-id]')
  await expect(image).toBeVisible()
  await expect(page.getByRole('button', { name: 'Deshacer' })).toBeEnabled()
  await page.keyboard.press('Control+Z')
  await expect(image).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Rehacer' })).toBeEnabled()
  await page.keyboard.press('Control+Shift+Z')
  await expect(image).toBeVisible()
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Exportar JSON' }).click()])
  const json = await download.path()
  if (!json) throw new Error('Export file missing')
  await page.goto('/')
  await page.getByRole('button', { name: 'Crear sala' }).click()
  await expect(page.getByText('En vivo')).toBeVisible()
  await page.locator('input[type="file"][accept="application/json,.json"]').setInputFiles(json)
  await expect(page.locator('[data-board-image-id]')).toBeVisible()
  const restoredImage = page.locator('[data-board-image-id]')
  const id = await restoredImage.getAttribute('data-board-image-id')
  await restoredImage.click()
  await expect(page.getByRole('button', { name: 'Eliminar imagen seleccionada' })).toBeVisible()
  await page.keyboard.press('Delete')
  await expect(page.locator(`[data-board-image-id="${id}"]`)).toHaveCount(0)
})
